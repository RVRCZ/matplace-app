# a plate of two filaments as the farm hands it over (docs/AL.md §10): Orca's per-extruder lines, the tool changes kept,
# the farm's line naming the slot of every paint
TWO = b"""; HEADER_BLOCK_START
; generated by OrcaSlicer 2.4.0-beta on 2026-10-19 at 09:12:03
; total layer number: 50
; matplace filaments T0=2 T1=5
; max_z_height: 4.00
; HEADER_BLOCK_END

; EXECUTABLE_BLOCK_START
G9111 bedTemp=55 extruderTemp=225
M117
T0 ; colour by matplace farm
; first_layer_print_min = 100,100
; first_layer_print_max = 140,120
;LAYER_CHANGE
;Z:0.2
G1 X1 Y1 E1
T1 ; colour by matplace farm
G1 X2 Y2 E1
T0
G1 X3 Y3 E1
; EXECUTABLE_BLOCK_END

; filament used [mm] = 1500.00, 250.00
; filament used [g] = 4.47, 0.75
; total filament used [g] = 5.22
; estimated printing time (normal mode) = 25m 10s

; CONFIG_BLOCK_START
; curr_bed_type = Textured PEI Plate
; filament_colour = #F2754E;#003594
; filament_ids = GFPLA;GFPLA
; filament_type = PLA;PLA
; layer_height = 0.2
; nozzle_diameter = 0.4
; printer_model = Anycubic Kobra X
; CONFIG_BLOCK_END
"""


class PackageTest(unittest.TestCase):
    def test_a_plate_of_several_filaments_keeps_its_tool_changes_and_names_every_paint(self):
        f = facts_of(TWO)
        self.assertEqual(({0: 2, 1: 5}, [0, 1], 0, ["#F2754E", "#003594"], ["PLA", "PLA"], ["GFPLA", "GFPLA"]), (f.paints, f.tools, f.tool, f.colours, f.materials, f.filament_ids))
        self.assertEqual(([1.5, 0.25], [4.47, 0.75], 5.22), (f.metres_each, f.grams_each, f.grams))
        self.assertAlmostEqual(1.75, f.metres)
        self.assertEqual(({}, [1]), (filaments_of(ORCA), tools_of(ORCA)))
        self.assertEqual({0: 0, 1: 3, 2: 6}, filaments_of(b"; HEADER_BLOCK_START\n; matplace filaments T0=0 T1=3 T2=6\n"))
        # the spools' colours and materials are the paints; the T lines stay as they are
        g = prepared_gcode(TWO, "#000000", "PLA", filaments=[("#212721", "PLA Silk"), ("#658946", "PLA Metal")])
        self.assertIn(b"\nT0 ; colour by matplace farm\n", g)
        self.assertIn(b"\nT1 ; colour by matplace farm\nG1 X2 Y2 E1\nT0\n", g)
        self.assertIn(b'; paint_info = [{"material_type":"PLA","paint_color":[33,39,33],"paint_index":0},{"material_type":"PLA","paint_color":[101,137,70],"paint_index":1}]\n; HEADER_BLOCK_END', g)
        self.assertIn(b"; ams_info = begin\n; paint_info = [{\"material_type\":\"PLA\",\"paint_color\":[33,39,33],\"paint_index\":0},{\"material_type\":\"PLA\",\"paint_color\":[101,137,70],\"paint_index\":1}]\n; ams_info = end", g)
        self.assertIn(b"; statistics = begin\n; used_filament = 1.75\n; print_time = 25m 10s\n; model_size = 40.00,20.00,4.00\n; total_layers = 50\n", g)
        data, facts = package(TWO, "#000000", "PLA", filaments=[("#212721", "PLA Silk"), ("#658946", "PLA Metal")])
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            self.assertEqual(g, z.read("Metadata/plate_1.gcode"))
            plate = json.loads(z.read("Metadata/plate_1.json"))
            self.assertEqual((["#212721", "#658946"], [0, 1]), (plate["filament_colors"], plate["filament_ids"]))
            info = z.read("Metadata/slice_info.config").decode()
            self.assertIn('<filament id="1" tray_info_idx="GFPLA" type="PLA Silk" color="#212721" used_m="1.50" used_g="4.47" />\n'
                          '    <filament id="2" tray_info_idx="GFPLA" type="PLA Metal" color="#658946" used_m="0.25" used_g="0.75" />\n  </plate>', info)
            self.assertIn('key="weight" value="5.22"', info)
        self.assertEqual({0: 2, 1: 5}, facts.paints)

    def test_the_facts_come_from_orcas_own_lines(self):
        f = facts_of(ORCA)
        self.assertEqual((50, 326, "5m 26s", 0.63, 1), (f.layers, f.seconds, f.time_text, f.grams, f.tool))
        self.assertAlmostEqual(0.21248, f.metres)
        self.assertEqual((123.0, 123.0, 137.0, 137.0), f.bbox)
        self.assertEqual((10.0, 0.2, 0.4), (f.height, f.layer_height, f.nozzle))
        self.assertEqual(("Anycubic Kobra X", "textured_plate", False, "placed.stl", "GFPLA"), (f.printer_model, f.bed_type, f.support, f.object_name, f.filament_id))
        self.assertEqual(0, tool_of(b"G28\nG1 X1\n"))

    def test_the_gcode_gets_paint_0_the_paint_info_lines_and_the_statistics_once(self):
        g = prepared_gcode(ORCA, "#FF7F32", "PLA Silk")
        self.assertIn(b"\nT0 ; slot chosen by matplace farm\n", g)
        self.assertNotIn(b"\nT1", g)
        self.assertIn(b'; filament: 1\n; paint_info = [{"material_type":"PLA","paint_color":[255,127,50],"paint_index":0}]\n; HEADER_BLOCK_END', g)
        self.assertTrue(g.endswith(b"; CONFIG_BLOCK_END\n\n\n\n; ams_info = begin\n; paint_info = [{\"material_type\":\"PLA\",\"paint_color\":[255,127,50],\"paint_index\":0}]\n; ams_info = end\n\n"
                                   b"; statistics = begin\n; used_filament = 0.21\n; print_time = 5m 26s\n; model_size = 14.00,14.00,10.00\n; total_layers = 50\n; statistics = end\n"), g[-400:])
        self.assertEqual(g, prepared_gcode(g, "#000000", "PETG"), "a file that has the lines keeps them")
        bare = prepared_gcode(b"G28\nG1 X1\n", "#000000", "PLA")
        self.assertTrue(bare.startswith(b"; HEADER_BLOCK_START\n; paint_info = "))

    def test_the_metadata_is_the_gcode_without_its_toolpath(self):
        g = prepared_gcode(ORCA, "#FF7F32", "PLA")
        m = metadata_of(g)
        self.assertIn(b"T0 ; slot chosen", m)
        self.assertIn(b"; filament start gcode", m)
        self.assertNotIn(b"G1 X1 Y1 E1", m)
        self.assertIn(b"; statistics = end", m)

    def test_the_package_has_what_the_slicer_next_uploads(self):
        data, facts = package(ORCA, "#FF7F32", "PLA Silk")
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            names = z.namelist()
            self.assertEqual(["[Content_Types].xml", "Metadata/plate_1.png", "Metadata/plate_1_small.png", "Metadata/plate_no_light_1.png", "Metadata/top_1.png",
                              "Metadata/pick_1.png", "Metadata/plate_1.json", "3D/3dmodel.model", "Metadata/custom_gcode_per_layer.xml", "Metadata/plate_1.gcode.md5",
                              "Metadata/plate_1.gcode.metadata", "Metadata/plate_1.gcode", "Metadata/_rels/model_settings.config.rels", "Metadata/model_settings.config",
                              "Metadata/slice_info.config", "_rels/.rels"], names)
            gcode = z.read("Metadata/plate_1.gcode")
            self.assertEqual(hashlib.md5(gcode).hexdigest().upper().encode(), z.read("Metadata/plate_1.gcode.md5"))
            self.assertEqual(prepared_gcode(ORCA, "#FF7F32", "PLA Silk"), gcode)
            plate = json.loads(z.read("Metadata/plate_1.json"))
            self.assertEqual([123.0, 123.0, 137.0, 137.0], plate["bbox_all"])
            self.assertEqual(("textured_plate", ["#FF7F32"], [0], 0, 2), (plate["bed_type"], plate["filament_colors"], plate["filament_ids"], plate["first_extruder"], plate["version"]))
            self.assertEqual("placed.stl", plate["bbox_objects"][0]["name"])
            info = z.read("Metadata/slice_info.config").decode()
            for piece in ('key="printer_model_id" value="Anycubic Kobra X"', 'key="prediction" value="326"', 'key="weight" value="0.63"',
                          '<filament id="1" tray_info_idx="GFPLA" type="PLA Silk" color="#FF7F32" used_m="0.21" used_g="0.63" />', 'name="placed.stl"'):
                self.assertIn(piece, info)
            for png in ("Metadata/plate_1.png", "Metadata/plate_1_small.png"):
                self.assertTrue(z.read(png).startswith(b"\x89PNG\r\n\x1a\n"))
            self.assertIn(b'gcode_file" value="Metadata/plate_1.gcode"', z.read("Metadata/model_settings.config"))
        self.assertEqual(1, facts.tool)


if __name__ == "__main__":
    unittest.main()
