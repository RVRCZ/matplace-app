<?php

namespace Tests\Unit;

use App\Domain\Farm\GcodeSlot;
use App\Engines\Mesh\StlFile;
use App\Engines\Mesh\ThreeMfWriter;
use App\Engines\Slicer\GcodeStats;
use PHPUnit\Framework\TestCase;

/**
 * A plate of several filaments on its way to the printer (docs/AL.md §10): the 3MF the slicer gets, the figures read
 * back from its G-code, and the copy that maps every T<n> to the slot its spool sits in and says so in the header
 * (the Kobra X agent reads `; matplace filaments T0=2 T1=5`, Rinkhals takes the T lines).
 */
class GcodeSlotTest extends TestCase
{
    private function gcode(): string
    {
        return "; HEADER_BLOCK_START\n; generated by test\n; HEADER_BLOCK_END\nG9111 bedTemp=55 extruderTemp=215\nM117\nT0\nM104 S205\nG1 X1 Y1 E1\n"
            .";LAYER_CHANGE\n;Z:0.4\n;HEIGHT:0.2\n; CP TOOLCHANGE START\nT1\nM104 S205\nG1 X2 Y2 E1\n; CP TOOLCHANGE END\nT0\nM104 S205 ; set nozzle temperature\nM140 S55 ; set bed temperature\nG1 X3 Y3 E1\n"
            ."M104 S0 ; turn off temperature\n; filament used [mm] = 2874.66, 1294.13\n; filament used [g] = 8.57, 3.86\n; total filament used [g] = 12.43\n; total filament change = 15\n"
            ."; estimated printing time (normal mode) = 55m 21s\n; filament_colour = #FFD700;#202020\n; filament_type = PLA;PLA\n";
    }

    public function test_every_tool_line_goes_to_its_slot_and_the_header_names_them(): void
    {
        $out = GcodeSlot::retargetMany($this->gcode(), [0 => 2, 1 => 5], [0 => ['nozzle' => 220, 'nozzle_first' => 225, 'bed' => 60], 1 => ['nozzle' => 230, 'nozzle_first' => 235, 'bed' => 60]]);
        $lines = explode("\n", $out);
        $this->assertSame('; HEADER_BLOCK_START', $lines[0]);
        $this->assertSame('; matplace filaments T0=2 T1=5', $lines[1], 'the map right after the first line, within the first 16 kB');
        $this->assertStringNotContainsString("\nT0\n", $out);
        $this->assertStringNotContainsString("\nT1\n", $out);
        $this->assertSame(2, preg_match_all('/^T2 ; matplace slot for filament 0$/m', $out));
        $this->assertSame(1, preg_match_all('/^T5 ; matplace slot for filament 1$/m', $out));
        // heated before the first spool is selected (the ACE refuses a cold nozzle), to the first filament's first-layer value
        $this->assertStringContainsString("M117\nM104 S225 ; matplace slot: heat before the spool change\nM109 S225 ; matplace slot: wait for it\nT2 ; matplace slot for filament 0\n", $out);
        $this->assertStringContainsString('G9111 bedTemp=60 extruderTemp=225', $out);
        // the temperatures follow the filament printing: 220 after T0, 230 after T1
        $this->assertMatchesRegularExpression('/T2 ; matplace slot for filament 0\nM104 S220\n/', $out);
        $this->assertMatchesRegularExpression('/T5 ; matplace slot for filament 1\nM104 S230\n/', $out);
        $this->assertStringContainsString("M104 S220 ; set nozzle temperature\nM140 S60 ; set bed temperature", $out);
        $this->assertStringContainsString("M104 S0 ; turn off temperature\n", $out, 'switching off stays');
        // the slicer's own lists stay as written: the agent reads the consumption per filament from them
        foreach (['; filament used [mm] = 2874.66, 1294.13', '; filament used [g] = 8.57, 3.86', '; filament_colour = #FFD700;#202020', '; filament_type = PLA;PLA', '; total filament change = 15'] as $kept) {
            $this->assertStringContainsString($kept."\n", $out);
        }

        // without temperatures the sliced ones stay; a T<n> the map does not know falls back to the first slot
        $plain = GcodeSlot::retargetMany(str_replace("T1\n", "T3\n", $this->gcode()), [0 => 1, 1 => 4]);
        $this->assertStringContainsString("M104 S205\n", $plain);
        $this->assertStringContainsString("T1 ; matplace slot for filament 3\n", $plain);
        $this->assertStringContainsString("heat before the spool change\nM109 S215", $plain, 'the start macro\'s temperature when none is given');
        $this->assertSame($this->gcode(), GcodeSlot::retargetMany($this->gcode(), []), 'no map: nothing changes');
    }

    public function test_the_copy_for_the_printer_is_written_once_and_the_stats_read_the_filaments_apart(): void
    {
        $dir = sys_get_temp_dir().'/mp_slot_'.uniqid();
        mkdir($dir);
        $src = $dir.'/print.gcode';
        file_put_contents($src, $this->gcode());
        $copy = GcodeSlot::fileForMany($src, [1 => 5, 0 => 2]);
        $this->assertStringEndsWith('print.hot.multi0to2_1to5.gcode', $copy);
        $this->assertStringContainsString('; matplace filaments T0=2 T1=5', (string) file_get_contents($copy));
        $time = filemtime($copy);
        $this->assertSame($copy, GcodeSlot::fileForMany($src, [0 => 2, 1 => 5]));
        $this->assertSame($time, filemtime($copy), 'reused while the original is older');
        $this->assertNotSame($copy, GcodeSlot::fileForMany($src, [0 => 2, 1 => 5], [0 => ['nozzle' => 220]]), 'other temperatures, another copy');

        $stats = GcodeStats::fromFile($src);
        $this->assertSame([8.57, 3.86], $stats['filament_grams']);
        $this->assertSame(15, $stats['changes']);
        $this->assertSame(12.43, $stats['grams']);
        $this->assertSame(55, $stats['minutes']);
        $this->assertEqualsWithDelta(4.169, $stats['meters'], 0.001);
        // a one-filament file: no list, no changes
        file_put_contents($dir.'/one.gcode', "; filament used [mm] = 100\n; filament used [g] = 1.5\n; total filament used [g] = 1.5\n; estimated printing time (normal mode) = 5m 0s\n");
        $one = GcodeStats::fromFile($dir.'/one.gcode');
        $this->assertSame([], $one['filament_grams']);
        $this->assertSame(0, $one['changes']);
        array_map('unlink', glob($dir.'/*'));
        rmdir($dir);
    }

    public function test_the_project_has_an_object_per_part_each_with_its_filament(): void
    {
        $dir = sys_get_temp_dir().'/mp_3mf_'.uniqid();
        mkdir($dir);
        StlFile::writeBox($dir.'/body.stl', 20, 20, 3);
        StlFile::writeBox($dir.'/inlay.stl', 6, 20, 3);
        ThreeMfWriter::write($dir.'/plate.3mf', [['name' => 'body', 'stl' => $dir.'/body.stl', 'extruder' => 1], ['name' => 'inlay & co', 'stl' => $dir.'/inlay.stl', 'extruder' => 2]]);
        $zip = new \ZipArchive;
        $this->assertTrue($zip->open($dir.'/plate.3mf'));
        $model = (string) $zip->getFromName('3D/3dmodel.model');
        $config = (string) $zip->getFromName('Metadata/model_settings.config');
        $this->assertNotEmpty($zip->getFromName('[Content_Types].xml'));
        $this->assertNotEmpty($zip->getFromName('_rels/.rels'));
        $zip->close();
        $this->assertSame(2, substr_count($model, '<object id='));
        $this->assertSame(16, substr_count($model, '<vertex '), 'eight corners a box, shared between its triangles');
        $this->assertSame(24, substr_count($model, '<triangle '));
        $this->assertStringContainsString('<item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/><item objectid="2"', $model);
        $this->assertStringContainsString('name="inlay &amp; co"', $model);
        $this->assertStringContainsString('<object id="1"><metadata key="name" value="body"/><metadata key="extruder" value="1"/></object>', $config);
        $this->assertStringContainsString('<object id="2"><metadata key="name" value="inlay &amp; co"/><metadata key="extruder" value="2"/></object>', $config);
        // the parts of a plate keep their places: moved together, concatenated for the check
        StlFile::translate($dir.'/inlay.stl', $dir.'/inlay-moved.stl', [7.0, 0.0, 0.0]);
        [$lo, $hi] = StlFile::bounds($dir.'/inlay-moved.stl');
        $this->assertEqualsWithDelta([7.0, 13.0], [$lo[0], $hi[0]], 0.001);
        $this->assertSame(24, StlFile::concat([$dir.'/body.stl', $dir.'/inlay-moved.stl'], $dir.'/plate.stl'));
        $this->assertEqualsWithDelta(20.0, StlFile::bounds($dir.'/plate.stl')[1][0], 0.001);
        array_map('unlink', glob($dir.'/*'));
        rmdir($dir);
    }
}
