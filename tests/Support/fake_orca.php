<?php

/**
 * A stand-in for the OrcaSlicer binary, run by the tests through a .cmd / .sh wrapper (OrcaBinToolchangerTest,
 * FarmToolChangerPlateTest): it takes the farm's command line as the real slicer does, reads the project it was given
 * and writes a G-code whose header has the shape of Orca 2.5's (docs/AM.md §12j) – a figure per filament loaded, 0.00
 * for a filament nothing prints from, `T<n> S1 L0 D0` for every tool used, the change count – so the whole path from
 * PrepareFarmOrder through OrcaSlicer::slice to GcodeStats runs against the command really built. With MP_FAKE_ORCA_DIR
 * set it leaves a copy of the process file, the filament files and the project there for the test to look at.
 * MP_FAKE_ORCA_PID names a file it writes its process id to, MP_FAKE_ORCA_SLEEP seconds it waits before it does anything.
 */
$args = array_slice($argv, 1);
// a slicer that takes its time, for the tests that stop it (SupersededSliceTest): it says who it is, then sleeps
if ($pidFile = getenv('MP_FAKE_ORCA_PID')) {
    file_put_contents($pidFile, (string) getmypid());
}
if (($sleep = (int) getenv('MP_FAKE_ORCA_SLEEP')) > 0) {
    sleep($sleep);
}
$opt = [];
for ($i = 0; $i < count($args); $i++) {
    if (str_starts_with($args[$i], '--') && isset($args[$i + 1])) {
        $opt[substr($args[$i], 2)] = $args[++$i];
    } else {
        $opt['input'] = $args[$i];
    }
}
$out = $opt['outputdir'] ?? sys_get_temp_dir();
@mkdir($out, 0777, true);
$filaments = array_values(array_filter(explode(';', (string) ($opt['load-filaments'] ?? ''))));
$settings = array_values(array_filter(explode(';', (string) ($opt['load-settings'] ?? ''))));
$process = $settings[1] ?? null;
$input = (string) ($opt['input'] ?? '');
$n = max(1, count($filaments));

// which extruders the project names (an object per part, a tool change per layer entry); a mesh prints from the first
$used = [1];
$changes = 0;
if (str_ends_with(strtolower($input), '.3mf') && class_exists('ZipArchive')) {
    $zip = new ZipArchive;
    if ($zip->open($input) === true) {
        $config = (string) $zip->getFromName('Metadata/model_settings.config');
        preg_match_all('/<metadata key="extruder" value="(\d+)"/', $config, $m);
        $used = array_values(array_unique(array_map('intval', $m[1]))) ?: [1];
        $layers = (string) $zip->getFromName('Metadata/custom_gcode_per_layer.xml');
        if (preg_match_all('/<layer [^>]*type="2"[^>]*extruder="(\d+)"/', $layers, $mm)) {
            $used = array_values(array_unique(array_merge($used, array_map('intval', $mm[1]))));
            $changes += count($mm[1]);
        }
        $zip->close();
    }
}
sort($used);
$layerCount = 30;
if (count($used) > 1) {
    $changes += (count($used) - 1) * $layerCount;
}
$colours = [];
$types = [];
foreach ($filaments as $f) {
    $j = json_decode((string) @file_get_contents($f), true) ?: [];
    $colours[] = (string) (($j['filament_colour'] ?? ['#FFFFFF'])[0] ?? '#FFFFFF');
    $types[] = (string) (($j['filament_type'] ?? ['PLA'])[0] ?? 'PLA');
}
$grams = [];
for ($i = 1; $i <= $n; $i++) {
    $grams[] = in_array($i, $used, true) ? '1.00' : '0.00';
}
$proc = $process ? (json_decode((string) @file_get_contents($process), true) ?: []) : [];
$tower = (string) ($proc['enable_prime_tower'] ?? '0');
$body = "; HEADER_BLOCK_START\n; generated by the fake OrcaSlicer of the tests\n; total layer number: {$layerCount}\n; HEADER_BLOCK_END\n";
$body .= 'M862.3 P "COREONEINDX"'."\n";
foreach ($used as $t) {
    $body .= 'M862.1 T'.($t - 1)." P0.4 A0 F1\n";
}
$body .= 'T'.($used[0] - 1)." S1 L2 D0\n";
for ($layer = 1; $layer <= $layerCount; $layer++) {
    $z = round($layer * 0.2, 2);
    $body .= ";LAYER_CHANGE\n;Z:{$z}\n;HEIGHT:0.2\nG1 Z{$z} F600\n";
    foreach ($used as $k => $t) {
        if ($k === 0 && $layer === 1) {
            $body .= 'T'.($t - 1)." S1 L0 D0\n";
        } elseif ($k > 0) {
            $body .= '  T'.($t - 1)." S1 L0 D0\n  G12 S90 ; enter cleaner\n  G12 S30 ; eject poop\n  G12 S91 ; Exit cleaning station\n";
        }
        $body .= "G1 X10 Y10 E1\n";
    }
}
if ($tower === '1') {
    $body .= ";TYPE:Prime tower\nG1 X15 Y15 E1\n";
}
$body .= '; filament used [mm] = '.implode(', ', array_map(fn ($g) => $g === '0.00' ? '0.00' : '374.35', $grams))."\n";
$body .= '; filament used [g] = '.implode(', ', $grams)."\n";
$body .= '; total filament used [g] = '.number_format(count($used) * 1.0, 2, '.', '')."\n";
if ($n > 1) {
    $body .= "; total filament change = {$changes}\n";
}
$body .= "; estimated printing time (normal mode) = 18m 5s\n";
$body .= "; CONFIG_BLOCK_START\n; enable_prime_tower = {$tower}\n; filament_colour = ".implode(';', $colours ?: ['#FFFFFF'])."\n; filament_type = ".implode(';', $types ?: ['PLA'])."\n";
foreach (['wipe_tower_x', 'wipe_tower_y', 'flush_into_infill', 'sparse_infill_density', 'layer_height'] as $k) {
    if (isset($proc[$k])) {
        $body .= '; '.$k.' = '.(is_array($proc[$k]) ? implode(',', $proc[$k]) : $proc[$k])."\n";
    }
}
$body .= "; CONFIG_BLOCK_END\n";
file_put_contents(rtrim($out, '/\\').'/plate_1.gcode', $body);

if ($dir = getenv('MP_FAKE_ORCA_DIR')) {
    @mkdir($dir, 0777, true);
    $run = $dir.'/run_'.str_pad((string) count(glob($dir.'/run_*')), 2, '0', STR_PAD_LEFT);
    @mkdir($run, 0777, true);
    file_put_contents($run.'/args.json', json_encode($args, JSON_PRETTY_PRINT));
    if ($process && is_file($process)) {
        copy($process, $run.'/process.json');
    }
    foreach ($filaments as $i => $f) {
        if (is_file($f)) {
            copy($f, $run.'/filament_'.($i + 1).'.json');
        }
    }
    if ($input && is_file($input)) {
        copy($input, $run.'/'.basename($input));
    }
}
echo 'fake orca: '.count($filaments).' filaments, tools '.implode(',', array_map(fn ($t) => 'T'.($t - 1), $used))."\n";
exit(0);
