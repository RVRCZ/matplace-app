    /** @param  'cube'|'hole'|'inlay'|'height'  $kind */
    public static function make(string $kind, string $flavour = 'orca', int $layers = 100): string
    {
        $g = array_merge(self::HEADERS[$flavour], ['G90', 'M83', 'G21', 'T0', 'M104 S210']);
        $half = self::WIDTH / 2;
        $outer = self::square($half, $half, 20 - $half, 20 - $half);
        $hole = self::square(6 - $half, 6 - $half, 14 + $half, 14 + $half);
        $letter = self::square(7 + $half, 7 + $half, 13 - $half, 13 - $half);
        $letterHole = self::square(7 - $half, 7 - $half, 13 + $half, 13 + $half);
        for ($i = 0; $i < $layers; $i++) {
            $z = round(($i + 1) * self::HEIGHT, 2);
            $blocks = $i === 0 ? [self::skirtAndSupport()] : [];
            switch ($kind) {
                case 'cube':
                    $blocks[] = self::loop($outer);
                    $blocks[] = self::innerWall(1.0, 1.0, 19.0, 19.0);
                    $blocks[] = self::infill(0, 0, 20, 20);
                    break;
                case 'hole':
                    $blocks[] = self::loop($outer);
                    $blocks[] = self::loop($hole);
                    $blocks[] = self::innerWall(1.0, 1.0, 19.0, 19.0);
                    $blocks[] = self::infill(0, 0, 20, 20);
                    break;
                case 'inlay':
                    if ($i < intdiv($layers, 2)) {
                        $blocks[] = self::loop($outer);
                        $blocks[] = self::infill(0, 0, 20, 20);
                    } else {
                        $blocks[] = ['T0'];
                        $blocks[] = self::loop($outer);
                        $blocks[] = self::loop($letterHole);
                        $blocks[] = self::infill(0, 0, 20, 20);
                        $blocks[] = ['T1'];
                        $blocks[] = self::loop($letter);
                        $blocks[] = ['T0'];
                    }
                    break;
                case 'height':
                    $blocks[] = [$i < intdiv($layers, 2) ? 'T0' : 'T1'];
                    $blocks[] = self::loop($outer);
                    $blocks[] = self::infill(0, 0, 20, 20);
                    break;
            }
            $lines = array_merge([';LAYER_CHANGE', sprintf(';Z:%.2f', $z), sprintf(';HEIGHT:%.2f', self::HEIGHT), sprintf('G1 Z%.2f F600', $z)], ...$blocks);
            if ($flavour === 'prusa') {
                $lines = str_replace([';TYPE:Outer wall', ';TYPE:Inner wall', ';TYPE:Sparse infill', ';TYPE:Support', ';TYPE:Skirt'], [';TYPE:External perimeter', ';TYPE:Perimeter', ';TYPE:Internal infill', ';TYPE:Support material', ';TYPE:Skirt/Brim'], $lines);
            }
            $g = array_merge($g, $lines);
        }
        $g[] = 'M104 S0';
        $g[] = '; end';

        return implode("\n", $g)."\n";
    }

    /** @return list<array{0: float, 1: float}> */
    private static function square(float $x0, float $y0, float $x1, float $y1): array
    {
        return [[$x0, $y0], [$x1, $y0], [$x1, $y1], [$x0, $y1]];
    }

    /** A closed outer-wall loop: a travel to its start, then extruding moves round and back to it. */
    private static function loop(array $pts): array
    {
        $out = [sprintf('G1 X%.3f Y%.3f F18000', $pts[0][0], $pts[0][1]), ';TYPE:Outer wall', sprintf(';WIDTH:%.2f', self::WIDTH), 'G1 F9000'];
        foreach (array_merge(array_slice($pts, 1), [$pts[0]]) as $p) {
            $out[] = sprintf('G1 X%.3f Y%.3f E0.15000', $p[0], $p[1]);
        }

        return $out;
    }

    private static function innerWall(float $x0, float $y0, float $x1, float $y1): array
    {
        $out = [';TYPE:Inner wall', ';WIDTH:0.45', sprintf('G1 X%.3f Y%.3f F18000', $x0, $y0)];
        foreach (array_merge(array_slice(self::square($x0, $y0, $x1, $y1), 1), [[$x0, $y0]]) as $p) {
            $out[] = sprintf('G1 X%.3f Y%.3f E0.2', $p[0], $p[1]);
        }

        return $out;
    }

    private static function infill(float $x0, float $y0, float $x1, float $y1): array
    {
        $out = [';TYPE:Sparse infill', ';WIDTH:0.45', sprintf('G1 X%.3f Y%.3f F18000', $x0 + 2, $y0 + 2)];
        $flip = false;
        for ($y = $y0 + 2; $y < $y1 - 2; $y += 3) {
            $out[] = sprintf('G1 X%.3f Y%.3f E0.1', $flip ? $x0 + 2 : $x1 - 2, $y);
            $out[] = sprintf('G1 X%.3f Y%.3f E0.05', $flip ? $x0 + 2 : $x1 - 2, $y + 3);
            $flip = ! $flip;
        }

        return $out;
    }

    private static function skirtAndSupport(): array
    {
        return [';TYPE:Skirt', 'G1 X-5 Y-5 F18000', 'G1 X25 Y-5 E0.3', 'G1 X25 Y25 E0.3', 'G1 X-5 Y25 E0.3', 'G1 X-5 Y-5 E0.3',
